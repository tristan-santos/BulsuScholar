def build_pdf():
    output = Path(__file__).resolve().parents[1] / 'docs' / 'BulsuScholar_Test_Case_Summary.pdf'
    styles = getSampleStyleSheet()
    body = ParagraphStyle('TableBody', fontName='Times-Roman', fontSize=10, leading=12)
    head = ParagraphStyle('TableHead', parent=body, fontName='Times-Bold', fontSize=11, leading=13)
    title = ParagraphStyle('ReportTitle', parent=styles['Title'], fontName='Times-Bold', fontSize=18, leading=22, alignment=TA_CENTER)
    note = ParagraphStyle('ReportNote', parent=body, fontSize=10, leading=13, spaceAfter=7)
    doc = SimpleDocTemplate(str(output), pagesize=landscape(A4), rightMargin=15*mm,
                            leftMargin=15*mm, topMargin=14*mm, bottomMargin=16*mm,
                            title='BulsuScholar Test Case Summary', author='BulsuScholar')
    story = [Paragraph('BulsuScholar Test Case Summary', title),
             Paragraph('Test run: October 20, 2026 | 284 automated backend tests passed', note),
             Paragraph('The TC numbers are summary IDs assigned to grouped core functions. Pass refers to automated backend testing, including mocked services and migration contract checks; it does not claim that every workflow was tested in the live browser.', note),
             Spacer(1, 3*mm)]
    headings = ['Test Case ID', 'Core Function', 'Expected Result', 'Actual Result', 'Status']
    data = [[Paragraph(h, head) for h in headings]]
    for index, (function, expected) in enumerate(ROWS, 1):
        data.append([Paragraph(escape(value), body) for value in
                     [f'TC-{index:02d}', function, expected, 'As expected', 'Pass']])
    table = LongTable(data, colWidths=[25*mm, 58*mm, 140*mm, 28*mm, 16*mm], repeatRows=1, hAlign='LEFT')
    table.setStyle(TableStyle([
        ('GRID', (0, 0), (-1, -1), .5, colors.HexColor('#555555')),
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#eeeeee')),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 7),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 7),
    ]))
    story.extend([table, Spacer(1, 4*mm), Paragraph(
        '<b>Coverage gap:</b> Recommended scholarship ranking is not marked Pass here. The current suite does not contain a dedicated test covering its complete scoring formula and ranking order.', note)])

    def footer(canvas, document):
        canvas.saveState()
        canvas.setFont('Times-Roman', 9)
        canvas.drawString(15*mm, 9*mm, 'BulsuScholar | Automated Test Summary')
        canvas.drawRightString(282*mm, 9*mm, f'Page {document.page}')
        canvas.restoreState()

    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    print(output)


if __name__ == '__main__':
    build_pdf()
